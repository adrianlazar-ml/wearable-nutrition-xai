"""T11.6 (2026-11-03): exhaustive text diff of the five Revision 1 docx files against a git revision, on every word/*.xml
part (document, comments, footers, headers, footnotes, endnotes, numbering, styles ...). For each part the text content
is the concatenation of the w:t runs per paragraph (w:p); parts are compared paragraph by paragraph (unified diff, 0 lines
of context). Parts present on one side only are listed. Styles and settings parts are compared as raw XML (reported as
'XML differs' with the length of the diff, since they carry no text).

Usage (repo root): python revision/scripts/_check_t11_docx_diff.py [--rev eeb3b98] [--out revision/audit/t11_docx_text_diff.md]
Exit 0 always (the report is the evidence; the brief lists the admitted differences).
"""
from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
import zipfile
from io import BytesIO
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAN = ROOT / "revision" / "manuscript"
FILES = ["KBS_Manuscript_R1.docx", "KBS_Manuscript_R1_marked.docx", "KBS_Response_R1.docx",
         "KBS_Supplementary_R1.docx", "KBS_Highlights_R1.docx"]
TEXT_PARTS = re.compile(r"^word/(document|comments|footer\d*|header\d*|footnotes|endnotes)\.xml$")


def paragraphs_text(xml: str) -> list[str]:
    out = []
    for p in re.findall(r"<w:p[ >].*?</w:p>", xml, re.S):
        t = "".join(re.findall(r"<w:t(?: [^>]*)?>([^<]*)</w:t>", p))
        out.append(t)
    return out


def parts(data: bytes) -> dict[str, bytes]:
    with zipfile.ZipFile(BytesIO(data)) as z:
        return {n: z.read(n) for n in z.namelist() if n.startswith("word/")}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rev", default="eeb3b98")
    ap.add_argument("--out", default=str(ROOT / "revision" / "audit" / "t11_docx_text_diff.md"))
    a = ap.parse_args()
    L = [f"# t11_docx_text_diff.md - text differences of the five docx against {a.rev} (all word/*.xml parts)", "",
         "Generated by `revision/scripts/_check_t11_docx_diff.py`. For the text parts (document, comments, footers, headers, footnotes, "
         "endnotes) the comparison is paragraph by paragraph on the w:t content; the other parts (styles, settings, numbering, theme, "
         "fontTable, webSettings, rels) are compared as raw XML and only reported as identical or different.", ""]
    total = 0
    for f in FILES:
        old = subprocess.run(["git", "show", f"{a.rev}:revision/manuscript/{f}"], cwd=ROOT, capture_output=True).stdout
        new = (MAN / f).read_bytes()
        po, pn = parts(old), parts(new)
        L.append(f"## {f}")
        L.append("")
        for name in sorted(set(po) | set(pn)):
            if name not in po:
                L.append(f"- `{name}`: only in the current file ({len(paragraphs_text(pn[name].decode('utf-8', 'replace')))} paragraphs)"); total += 1; continue
            if name not in pn:
                L.append(f"- `{name}`: only in {a.rev}"); total += 1; continue
            if TEXT_PARTS.match(name):
                to, tn = paragraphs_text(po[name].decode("utf-8", "replace")), paragraphs_text(pn[name].decode("utf-8", "replace"))
                if to == tn:
                    continue
                d = [l for l in difflib.unified_diff(to, tn, lineterm="", n=0) if not l.startswith(("---", "+++", "@@"))]
                total += 1
                L.append(f"- `{name}`: {len(to)} -> {len(tn)} paragraphs; {sum(l.startswith('-') for l in d)} removed, {sum(l.startswith('+') for l in d)} added:")
                for l in d:
                    L.append(f"    - `{l[0]}` {l[1:][:300].replace('|', '/')}" + ("..." if len(l) > 301 else ""))
            else:
                if po[name] != pn[name]:
                    total += 1
                    L.append(f"- `{name}`: XML differs ({len(po[name])} -> {len(pn[name])} bytes; no text content compared)")
        if L[-1] == "":
            L.append("- all word/*.xml parts identical in text")
        L.append("")
    L.insert(3, f"Parts with a difference: {total}.")
    L.insert(4, "")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"{total} parts differ -> {a.out}")
    sys.exit(0)


if __name__ == "__main__":
    main()
